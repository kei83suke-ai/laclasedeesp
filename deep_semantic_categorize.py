# Now we chunk them without alphabets. Just number them if > 35
cat_items = {}
for pos, items in data.items():
    cat_items[pos] = {}
    for item in items:
        cat = item['category']
        if cat not in cat_items[pos]:
            cat_items[pos][cat] = []
        cat_items[pos][cat].append(item)

for pos in data:
    data[pos] = []

for pos, categories_dict in cat_items.items():
    for cat, items in categories_dict.items():
        if len(items) > 35:
            # We must split into parts (1), (2), (3)
            # Shuffle slightly or keep alphabetical? The user doesn't want alphabetical logic in the TITLE.
            # But we can sort them internally for consistency.
            def get_sort_key(item):
                s = item.get('es', '').lower()
                for prefix in ['el/la ', 'los/las ', 'el ', 'la ', 'los ', 'las ', 'un ', 'una ', 'unos ', 'unas ']:
                    if s.startswith(prefix): s = s[len(prefix):]
                return s.lstrip('¿¡')
            items.sort(key=get_sort_key)
            
            chunk_size = 35
            num_chunks = (len(items) + chunk_size - 1) // chunk_size
            for i in range(num_chunks):
                chunk = items[i*chunk_size : (i+1)*chunk_size]
                # Format: "🎯 実用名詞 (その1)"
                new_cat = f"{cat} (その{i+1})"
                for item in chunk:
                    item['category'] = new_cat
                    data[pos].append(item)
        else:
            for item in items:
                item['category'] = cat
                data[pos].append(item)

